import { useState, useEffect, useRef } from 'react';
import { ImageDropzone } from './ImageDropzone';
import { SkinToneSelector } from './SkinToneSelector';
import { ArrowRight, Info, AlertCircle, Loader2, X, RotateCcw } from 'lucide-react';
import { predict } from '../../api/apiClient';
import type { PredictResponse } from '../../api/types';

export interface UploadScreenProps {
  onAnalyzeSuccess: (result: PredictResponse, previewUrl?: string) => void;
}

export function UploadScreen({ onAnalyzeSuccess }: UploadScreenProps) {
  const [dermoscopicImage, setDermoscopicImage] = useState<File | null>(null);
  const [clinicalImage, setClinicalImage] = useState<File | null>(null);
  const [skinTone, setSkinTone] = useState<number | undefined>(undefined);
  const [isLoading, setIsLoading] = useState<boolean>(false);
  const [elapsedSeconds, setElapsedSeconds] = useState<number>(0);
  const [errorMessage, setErrorMessage] = useState<string | null>(null);
  const [activePreviewUrl, setActivePreviewUrl] = useState<string | null>(null);

  const timerRef = useRef<number | null>(null);

  // Manage elapsed seconds timer during loading state
  useEffect(() => {
    if (isLoading) {
      const interval = window.setInterval(() => {
        setElapsedSeconds((prev) => prev + 1);
      }, 1000);
      timerRef.current = interval;
    } else {
      if (timerRef.current !== null) {
        window.clearInterval(timerRef.current);
        timerRef.current = null;
      }
    }

    return () => {
      if (timerRef.current !== null) {
        window.clearInterval(timerRef.current);
      }
    };
  }, [isLoading]);

  // Clean up any preview URL generated by this component on unmount
  useEffect(() => {
    return () => {
      if (activePreviewUrl) {
        URL.revokeObjectURL(activePreviewUrl);
      }
    };
  }, [activePreviewUrl]);

  const handleAnalyze = async () => {
    if (!dermoscopicImage) {
      setErrorMessage('Please upload a dermoscopic photograph before analyzing (required by model).');
      return;
    }

    setIsLoading(true);
    setErrorMessage(null);

    try {
      const response = await predict({
        dermoscopic_image: dermoscopicImage,
        clinical_image: clinicalImage ?? null,
        skin_tone: skinTone ?? null,
      });

      // Generate object URL for the primary analyzed image (dermoscopic)
      const previewUrl = URL.createObjectURL(dermoscopicImage);
      if (activePreviewUrl) {
        URL.revokeObjectURL(activePreviewUrl);
      }
      setActivePreviewUrl(previewUrl);

      onAnalyzeSuccess(response, previewUrl);
    } catch (err: unknown) {
      const msg =
        err instanceof Error
          ? err.message
          : 'Prediction request failed. Please verify server connectivity and retry.';
      setErrorMessage(msg);
    } finally {
      setIsLoading(false);
    }
  };

  return (
    <section aria-label="Upload Screen" className="flex flex-col gap-6 max-w-4xl mx-auto py-4">
      <header className="border-b border-slate-200 pb-4">
        <h2 className="text-xl md:text-2xl font-bold text-slate-900">
          Lesion Image Submission
        </h2>
        <p className="text-sm text-slate-600 mt-1">
          Provide primary dermoscopic photograph (required) and optional clinical context for AI evaluation.
        </p>
      </header>

      {/* Dismissible Error message alert with retry button */}
      {errorMessage && (
        <div
          role="alert"
          aria-live="polite"
          className="flex items-start justify-between gap-3 p-4 rounded-xl bg-red-50 border border-red-200 text-red-800 text-sm font-medium shadow-xs"
        >
          <div className="flex items-start gap-2.5">
            <AlertCircle className="w-5 h-5 shrink-0 text-red-600 mt-0.5" aria-hidden="true" />
            <div className="flex flex-col gap-1">
              <span className="font-semibold text-red-900">Inference Request Failed</span>
              <span className="text-xs text-red-800 leading-relaxed">{errorMessage}</span>
            </div>
          </div>

          <div className="flex items-center gap-2 shrink-0">
            <button
              type="button"
              onClick={handleAnalyze}
              disabled={isLoading || !dermoscopicImage}
              className="inline-flex items-center gap-1 px-2.5 py-1 text-xs font-semibold text-red-700 bg-white border border-red-300 rounded-lg hover:bg-red-50 transition-colors cursor-pointer outline-none focus-visible:ring-2 focus-visible:ring-red-600"
            >
              <RotateCcw className="w-3.5 h-3.5" aria-hidden="true" />
              <span>Retry</span>
            </button>
            <button
              type="button"
              onClick={() => setErrorMessage(null)}
              aria-label="Dismiss error message"
              className="p-1 text-red-600 hover:text-red-900 hover:bg-red-100 rounded-lg transition-colors cursor-pointer outline-none focus-visible:ring-2 focus-visible:ring-red-600"
            >
              <X className="w-4 h-4" aria-hidden="true" />
            </button>
          </div>
        </div>
      )}

      {/* Grid of dropzones */}
      <div className="grid grid-cols-1 md:grid-cols-2 gap-6">
        {/* 1. Primary Required Dropzone: Dermoscopic Image */}
        <div className="flex flex-col gap-2">
          <ImageDropzone
            id="dermoscopic-image-upload"
            label="Dermoscopic Photograph"
            description="High-magnification polarized dermoscopic view"
            required={true}
            file={dermoscopicImage}
            onFileChange={setDermoscopicImage}
            onError={setErrorMessage}
          />
        </div>

        {/* 2. Optional Secondary Dropzone: Clinical Image */}
        <div className="flex flex-col gap-2">
          <ImageDropzone
            id="clinical-image-upload"
            label="Clinical Overview Photograph"
            description="Optional - not used by the current model"
            required={false}
            file={clinicalImage}
            onFileChange={setClinicalImage}
            onError={setErrorMessage}
          />

          <div
            role="status"
            className="flex items-center gap-2 p-2.5 rounded-lg bg-slate-100 border border-slate-200 text-slate-700 text-xs font-medium"
          >
            <Info className="w-4 h-4 shrink-0 text-slate-500" aria-hidden="true" />
            <span>Optional - not used by the current model (recorded for future multimodal arms).</span>
          </div>
        </div>
      </div>

      {/* Skin tone selector */}
      <SkinToneSelector value={skinTone} onChange={setSkinTone} />

      {/* Action footer */}
      <div className="flex flex-col sm:flex-row items-center justify-between gap-4 pt-4 border-t border-slate-200">
        <div className="text-xs text-slate-500">
          {isLoading ? (
            <span className="font-medium text-sky-700">
              Processing inference on active backend... ({elapsedSeconds}s elapsed)
            </span>
          ) : (
            <span>Ready for submission &bull; Inference processed on CPU/GPU</span>
          )}
        </div>

        <button
          type="button"
          onClick={handleAnalyze}
          disabled={isLoading || !dermoscopicImage}
          className={`w-full sm:w-auto inline-flex items-center justify-center gap-2 px-6 py-3 font-semibold text-sm rounded-xl shadow-sm transition-all focus-visible:ring-2 focus-visible:ring-sky-600 focus-visible:ring-offset-2 outline-none ${
            isLoading || !dermoscopicImage
              ? 'bg-sky-400 text-white cursor-not-allowed opacity-80'
              : 'bg-sky-600 hover:bg-sky-700 active:bg-sky-800 text-white cursor-pointer'
          }`}
        >
          {isLoading ? (
            <>
              <Loader2 className="w-4 h-4 animate-spin" aria-hidden="true" />
              <span>Analyzing ({elapsedSeconds}s)...</span>
            </>
          ) : (
            <>
              <span>Analyze Dermoscopic Image</span>
              <ArrowRight className="w-4 h-4" aria-hidden="true" />
            </>
          )}
        </button>
      </div>
    </section>
  );
}

export default UploadScreen;
